#!/usr/bin/env node
// Regenerates the <link rel="modulepreload"> block in public/index.html.
//
// The app is made of many small ES modules that import each other. Without
// hints the browser discovers them level by level: it downloads app.js, reads
// its imports, downloads those, reads theirs, and so on. The preload block
// lists every module up front so they are all fetched at once.
//
// Run this after adding, removing or renaming a file under public/js:
//   npm run preloads          rewrite the block
//   npm run preloads:check    exit 1 if the block is out of date (changes nothing)
//
// A stale block is harmless but wasteful: a missing module just loads the old
// slow way, and a listed module that no longer exists costs one failed request.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join, normalize, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "public");
const ENTRY = join(ROOT, "js", "app.js");
const HTML = join(ROOT, "index.html");
const START = "<!-- modulepreload:start (generated by tools/update-preloads.mjs - do not edit by hand) -->";
const END = "<!-- modulepreload:end -->";

// Static imports only: `import ... from "./x.js"` and `import "./x.js"`.
const IMPORT_RE = /^\s*import\s+(?:[^"';]*?\sfrom\s+)?["']([^"']+)["']/gm;

function importsOf(file) {
  const source = readFileSync(file, "utf8");
  const found = [];
  for (const match of source.matchAll(IMPORT_RE)) {
    const spec = match[1];
    if (!spec.startsWith(".")) continue; // only our own files
    const target = normalize(join(dirname(file), spec));
    if (!existsSync(target)) throw new Error(`${relative(ROOT, file)} imports a missing file: ${spec}`);
    found.push(target);
  }
  return found;
}

// Breadth-first walk from app.js, so modules needed first are listed first.
const depth = new Map([[ENTRY, 0]]);
const queue = [ENTRY];
while (queue.length) {
  const file = queue.shift();
  for (const dep of importsOf(file)) {
    if (!depth.has(dep)) {
      depth.set(dep, depth.get(file) + 1);
      queue.push(dep);
    }
  }
}

const urls = [...depth.entries()]
  .filter(([file]) => file !== ENTRY) // app.js is requested by its own <script> tag
  .sort((a, b) => a[1] - b[1] || a[0].localeCompare(b[0]))
  .map(([file]) => "/" + relative(ROOT, file).split(sep).join("/"));

const block = [START, ...urls.map((url) => `<link rel="modulepreload" href="${url}">`), END]
  .map((line) => "  " + line)
  .join("\n");

const html = readFileSync(HTML, "utf8");
const start = html.indexOf("  " + START);
const end = html.indexOf(END);
if (start === -1 || end === -1) throw new Error(`Markers not found in ${relative(process.cwd(), HTML)}`);
const updated = html.slice(0, start) + block + html.slice(end + END.length);

const maxDepth = Math.max(...depth.values());
if (process.argv.includes("--check")) {
  if (updated !== html) {
    console.error("modulepreload block is out of date. Run: npm run preloads");
    process.exit(1);
  }
  console.log(`modulepreload block is up to date (${urls.length} modules, import depth ${maxDepth}).`);
} else {
  if (updated !== html) writeFileSync(HTML, updated);
  console.log(`${updated !== html ? "Updated" : "Already current"}: ${urls.length} modules, import depth ${maxDepth}.`);
}
